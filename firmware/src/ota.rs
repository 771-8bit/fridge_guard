use embedded_svc::http::client::Client as HttpClient;
use embedded_svc::http::Method;
use esp_idf_svc::http::client::{Configuration as HttpConfig, EspHttpConnection};
use esp_idf_sys::{
    esp_app_desc_t, esp_ota_abort, esp_ota_begin, esp_ota_end, esp_ota_get_last_invalid_partition,
    esp_ota_get_next_update_partition, esp_ota_get_partition_description,
    esp_ota_get_running_partition, esp_ota_get_state_partition, esp_ota_handle_t,
    esp_ota_img_states_t, esp_ota_img_states_t_ESP_OTA_IMG_PENDING_VERIFY,
    esp_ota_mark_app_invalid_rollback_and_reboot, esp_ota_mark_app_valid_cancel_rollback,
    esp_ota_set_boot_partition, esp_ota_write, ESP_OK, OTA_SIZE_UNKNOWN,
};
use fridge_guard_core::manifest::{
    parse_verifying_key_pem, ManifestValidationError, OtaManifest, OtaStreamVerifier,
    TARGET_HARDWARE_ID,
};
use log::{error, info, warn};
use std::ffi::CStr;
use std::time::Duration;

/// Trusted OTA release verification key (P-256, PEM). Generated by `tools/release.py --generate-key`;
/// presence and format are checked in `build.rs`.
const OTA_VERIFICATION_PUBLIC_KEY_PEM: &str = include_str!("../ota_verification_public.pem");

/// A manifest is a few hundred bytes; anything far larger is not a manifest
const MAX_MANIFEST_BYTES: usize = 8 * 1024;

/// Aborts an in-progress OTA write unless it was finished with `esp_ota_end`.
struct OtaWriteHandle {
    handle: esp_ota_handle_t,
    finished: bool,
}

impl Drop for OtaWriteHandle {
    fn drop(&mut self) {
        if !self.finished {
            unsafe {
                esp_ota_abort(self.handle);
            }
        }
    }
}

pub struct OtaManager;

impl OtaManager {
    /// True if the running image was just installed by OTA and still awaits confirmation.
    /// Until it is confirmed, any reboot makes the bootloader roll back to the previous image.
    pub fn is_running_image_pending_verify() -> bool {
        let mut state: esp_ota_img_states_t = 0;
        let err =
            unsafe { esp_ota_get_state_partition(esp_ota_get_running_partition(), &mut state) };
        err == ESP_OK && state == esp_ota_img_states_t_ESP_OTA_IMG_PENDING_VERIFY
    }

    /// Confirm the running image after a successful post-update self-test (cancels rollback).
    pub fn mark_running_image_valid() -> Result<(), String> {
        let err = unsafe { esp_ota_mark_app_valid_cancel_rollback() };
        if err == ESP_OK {
            Ok(())
        } else {
            Err(format!(
                "esp_ota_mark_app_valid_cancel_rollback failed: {err:x}"
            ))
        }
    }

    /// Reject the running image and reboot into the previous one. Does not return on success.
    pub fn rollback_and_reboot() -> String {
        let err = unsafe { esp_ota_mark_app_invalid_rollback_and_reboot() };
        format!("esp_ota_mark_app_invalid_rollback_and_reboot failed: {err:x}")
    }

    /// Version of the image the bootloader last rolled back from, if any.
    fn rolled_back_version() -> Option<String> {
        let partition = unsafe { esp_ota_get_last_invalid_partition() };
        if partition.is_null() {
            return None;
        }
        let mut desc: esp_app_desc_t = unsafe { std::mem::zeroed() };
        if unsafe { esp_ota_get_partition_description(partition, &mut desc) } != ESP_OK {
            return None;
        }
        let version = unsafe { CStr::from_ptr(desc.version.as_ptr()) };
        Some(version.to_string_lossy().into_owned())
    }

    /// Fetch manifest from HTTPS URL and check for newer compatible update.
    /// `Ok(_)` means the manifest was fetched successfully (used as the post-update network self-test).
    pub fn check_for_update(
        manifest_url: &str,
        current_version: &str,
    ) -> Result<Option<OtaManifest>, String> {
        info!("Fetching OTA manifest from: {manifest_url}");

        let http_config = HttpConfig {
            timeout: Some(Duration::from_secs(15)),
            use_global_ca_store: true,
            crt_bundle_attach: Some(esp_idf_sys::esp_crt_bundle_attach),
            ..Default::default()
        };

        let connection = EspHttpConnection::new(&http_config)
            .map_err(|e| format!("Failed to create HTTP connection for manifest: {e:?}"))?;
        let mut client = HttpClient::wrap(connection);

        let request = client
            .request(Method::Get, manifest_url, &[])
            .map_err(|e| format!("Failed to initiate GET request for manifest: {e:?}"))?;

        let mut response = request
            .submit()
            .map_err(|e| format!("Failed to submit GET request for manifest: {e:?}"))?;

        let status = response.status();
        if status != 200 {
            return Err(format!("Manifest server returned HTTP status {status}"));
        }

        let mut body = Vec::new();
        let mut buf = [0u8; 512];
        loop {
            let bytes_read = response
                .read(&mut buf)
                .map_err(|e| format!("Error reading manifest response: {e:?}"))?;
            if bytes_read == 0 {
                break;
            }
            if body.len() + bytes_read > MAX_MANIFEST_BYTES {
                return Err(format!(
                    "Manifest response exceeds {MAX_MANIFEST_BYTES} bytes"
                ));
            }
            body.extend_from_slice(&buf[..bytes_read]);
        }

        let json_str = std::str::from_utf8(&body)
            .map_err(|e| format!("Invalid UTF-8 in manifest response: {e}"))?;

        let trusted_key = parse_verifying_key_pem(OTA_VERIFICATION_PUBLIC_KEY_PEM)
            .map_err(|e| format!("Embedded OTA verification key is invalid: {e:?}"))?;

        match OtaManifest::parse_and_validate(
            json_str,
            current_version,
            TARGET_HARDWARE_ID,
            &trusted_key,
        ) {
            Ok(manifest) => {
                if Self::rolled_back_version().as_deref() == Some(manifest.version.as_str()) {
                    warn!(
                        "Skipping v{}: this version failed its post-update self-test and was rolled back",
                        manifest.version
                    );
                    return Ok(None);
                }
                info!(
                    "New signed firmware update found: v{} (release signature verified)",
                    manifest.version
                );
                Ok(Some(manifest))
            }
            Err(ManifestValidationError::EqualOrDowngradeVersion { .. }) => {
                info!("Firmware is already up to date ({current_version})");
                Ok(None)
            }
            Err(ManifestValidationError::MinimumVersionNotMet { current, required }) => {
                warn!(
                    "Update available but requires intermediate version v{required} (running v{current})"
                );
                Ok(None)
            }
            Err(ManifestValidationError::IncompatibleHardware { found, expected }) => {
                warn!("Manifest is for hardware '{found}', expected '{expected}'; skipping update");
                Ok(None)
            }
            Err(e) => {
                error!("Rejecting invalid or untrusted OTA manifest: {e:?}");
                Err(format!("OTA manifest validation failed: {e:?}"))
            }
        }
    }

    /// Download, verify and flash the update into the inactive OTA slot and make it the boot slot.
    /// On `Ok` the caller must save its state and restart; on `Err` the partially written slot
    /// is discarded and the running image stays active.
    pub fn perform_update(manifest: &OtaManifest) -> Result<(), String> {
        info!(
            "Starting OTA update to version: v{} from {}",
            manifest.version, manifest.asset_url
        );

        let update_partition = unsafe { esp_ota_get_next_update_partition(std::ptr::null()) };
        if update_partition.is_null() {
            return Err("Failed to find inactive OTA update partition".to_string());
        }

        let mut ota = OtaWriteHandle {
            handle: 0,
            finished: true,
        };
        let err =
            unsafe { esp_ota_begin(update_partition, OTA_SIZE_UNKNOWN as usize, &mut ota.handle) };
        if err != ESP_OK {
            return Err(format!("esp_ota_begin failed with error code: {err:x}"));
        }
        ota.finished = false;

        let http_config = HttpConfig {
            timeout: Some(Duration::from_secs(30)),
            use_global_ca_store: true,
            crt_bundle_attach: Some(esp_idf_sys::esp_crt_bundle_attach),
            ..Default::default()
        };

        let connection = EspHttpConnection::new(&http_config)
            .map_err(|e| format!("Failed to create HTTP connection for firmware: {e:?}"))?;
        let mut client = HttpClient::wrap(connection);

        let request = client
            .request(Method::Get, &manifest.asset_url, &[])
            .map_err(|e| format!("Failed to initiate GET request for firmware: {e:?}"))?;

        let mut response = request
            .submit()
            .map_err(|e| format!("Failed to submit GET request for firmware: {e:?}"))?;

        let status = response.status();
        if status != 200 {
            return Err(format!("Firmware download returned HTTP status {status}"));
        }

        let mut verifier = OtaStreamVerifier::new(&manifest.sha256);
        let mut total_bytes = 0usize;
        let mut buf = [0u8; 1024];

        loop {
            let bytes_read = response
                .read(&mut buf)
                .map_err(|e| format!("Error streaming firmware: {e:?}"))?;
            if bytes_read == 0 {
                break;
            }

            verifier.update(&buf[..bytes_read]);

            let write_err =
                unsafe { esp_ota_write(ota.handle, buf.as_ptr() as *const _, bytes_read) };
            if write_err != ESP_OK {
                return Err(format!("esp_ota_write failed with error: {write_err:x}"));
            }

            total_bytes += bytes_read;

            // Feed task watchdog and yield to FreeRTOS scheduler so background tasks (WiFi, lwIP) run
            unsafe {
                let _ = esp_idf_sys::esp_task_wdt_reset();
            }
            std::thread::sleep(Duration::from_millis(1));
        }

        info!(
            "Firmware download complete. Total bytes written: {total_bytes}. Verifying SHA-256..."
        );

        let (verified, calculated_sha256) = verifier.finalize_and_verify();
        if !verified {
            error!(
                "CRITICAL: Firmware SHA-256 mismatch! Expected: {}, Calculated: {}",
                manifest.sha256, calculated_sha256
            );
            return Err(format!(
                "OTA binary verification failed: SHA-256 checksum mismatch (got {calculated_sha256})"
            ));
        }

        info!("Firmware SHA-256 verified successfully ({calculated_sha256})");

        // esp_ota_end releases the handle whether or not it succeeds
        ota.finished = true;
        let end_err = unsafe { esp_ota_end(ota.handle) };
        if end_err != ESP_OK {
            return Err(format!("esp_ota_end failed with error: {end_err:x}"));
        }

        let boot_err = unsafe { esp_ota_set_boot_partition(update_partition) };
        if boot_err != ESP_OK {
            return Err(format!(
                "esp_ota_set_boot_partition failed with error: {boot_err:x}"
            ));
        }

        info!("OTA update flashed successfully; it boots on the next restart");
        Ok(())
    }
}
